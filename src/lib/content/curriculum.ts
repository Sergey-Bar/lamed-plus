export function getSubjectLessons(subjectId: string): Lesson[] {
  return LESSONS.filter((lesson) => lesson.subjectId === subjectId)
}

export function getLesson(lessonId: string): Lesson | undefined {
  return LESSONS.find((lesson) => lesson.id === lessonId)
}

export function nextLesson(lessonId: string): Lesson | undefined {
  const index = LESSONS.findIndex((lesson) => lesson.id === lessonId)
  if (index < 0) return undefined
  return LESSONS[index + 1]
}

export function subjectProgress(lessons: Lesson[], completed: string[]): number {
  if (lessons.length === 0) return 0
  return Math.round((lessons.filter((lesson) => completed.includes(lesson.id)).length / lessons.length) * 100)
}

/** Resolve a lesson into the requested language, falling back to Hebrew. */
export function localizeLesson(lesson: Lesson, language: LanguageId): Lesson {
  const translated = LESSON_TRANSLATIONS[language]?.[lesson.id]
  if (!translated) return lesson
  return { ...lesson, ...translated }
}

/** Subject insight in the requested language, falling back to Hebrew. */
export function getSubjectInsight(subjectId: string, language: LanguageId): string {
  return SUBJECT_INSIGHTS[language]?.[subjectId] ?? SUBJECT_META[subjectId]?.insights ?? ''
}
